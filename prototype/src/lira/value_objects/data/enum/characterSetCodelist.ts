/** The `CharacterSetCodelist` member whose IANA name or alias matches
 * `label` (case-insensitive, as IANA character set names are), or
 * `undefined` when `label` names no D25A character set. */
export function characterSetCodelistFromLabel(label: string): CharacterSetCodelist | undefined {
  const target = label.toLowerCase();
  for (const [code, labels] of Object.entries(CHARACTER_SET_LABELS)) {
    if (labels.some((candidate) => candidate.toLowerCase() === target)) return Number(code) as CharacterSetCodelist;
  }
  return undefined;
}
